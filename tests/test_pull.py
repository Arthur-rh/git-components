import os
import stat

import yaml

from gitcomponent import errors
from gitcomponent.cli import main


def _add_component(source_repo, ref="branch=main", name="mylib", extra_args=None):
    args = [
        "add", name, str(source_repo), ref,
        "--map", "src/core/:vendor/mylib/core/",
        "--exclude-glob", "**/*.md",
        "--map", "src/utils/:vendor/mylib/utils/",
        "--exclude-glob", "tests/**",
    ]
    if extra_args:
        args += extra_args
    assert main(args) == errors.EXIT_SUCCESS


def test_pull_copies_filtered_files(repo, source_repo):
    main(["init"])
    _add_component(source_repo)

    assert main(["pull"]) == errors.EXIT_SUCCESS

    assert (repo / "vendor/mylib/core/a.py").read_text() == "print('a')\n"
    assert (repo / "vendor/mylib/core/e.py").exists()
    assert not (repo / "vendor/mylib/core/b.md").exists()  # excluded
    assert (repo / "vendor/mylib/utils/c.txt").exists()
    assert not (repo / "vendor/mylib/utils/tests/d.txt").exists()  # excluded


def test_pulled_files_are_readonly(repo, source_repo):
    main(["init"])
    _add_component(source_repo)
    main(["pull"])

    path = repo / "vendor/mylib/core/a.py"
    mode = stat.S_IMODE(os.stat(path).st_mode)
    assert not (mode & stat.S_IWUSR)


def test_pull_writes_lock_with_hashes(repo, source_repo):
    main(["init"])
    _add_component(source_repo)
    main(["pull"])

    lock_data = yaml.safe_load((repo / ".git-components.lock").read_text())
    entry = lock_data["components"]["mylib"]
    assert entry["resolved-from"] == {"branch": "main"}
    assert len(entry["commit"]) == 40
    assert len(entry["imported-files"]["vendor/mylib/core/a.py"]) == 40  # sha1 hex


def test_pull_updates_gitignore(repo, source_repo):
    main(["init"])
    _add_component(source_repo)
