def test_pull_without_manifest_fails(repo):
    assert main(["pull"]) == errors.EXIT_MANIFEST_MISSING


def test_pull_detects_manifest_lock_drift_without_flags(repo, source_repo):
    main(["init"])
    _add_component(source_repo)
    main(["pull"])

    lock_path = repo / ".git-components.lock"
    data = yaml.safe_load(lock_path.read_text())
    data["components"]["mylib"]["commit"] = "0" * 40
    lock_path.write_text(yaml.safe_dump(data, sort_keys=False))

    assert main(["pull"]) == errors.EXIT_MANIFEST_LOCK_DISAGREE
    assert main(["pull", "--update-lock"]) == errors.EXIT_SUCCESS


def test_pull_ignore_manifest_keeps_locked_commit(repo, source_repo):
    main(["init"])
    _add_component(source_repo, ref="tag=v1.0")
    main(["pull"])

    lock_path = repo / ".git-components.lock"
    original = yaml.safe_load(lock_path.read_text())

    assert main(["pull", "--ignore-manifest"]) == errors.EXIT_SUCCESS
    after = yaml.safe_load(lock_path.read_text())
    assert after["components"]["mylib"]["commit"] == original["components"]["mylib"]["commit"]
    assert not (repo / "vendor/mylib/core/e.py").exists()


def test_pull_within_component_rule_conflict_keeps_higher_priority_rule(repo, source_repo):
    main(["init"])
    main([
        "add", "mylib", str(source_repo), "branch=main",
        "--map", "src/core/a.py:dest.py",
        "--map", "src/utils/c.txt:dest.py",
    ])
    assert main(["pull"]) == errors.EXIT_SUCCESS
    assert (repo / "dest.py").read_text() == "print('a')\n"
